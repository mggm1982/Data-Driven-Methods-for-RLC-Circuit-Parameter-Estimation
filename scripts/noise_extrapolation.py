"""Locked final amplitude stress test; see docs/noise_extrapolation.md."""
import argparse
import hashlib
import json
from pathlib import Path
import platform

import numpy as np
import torch

from scripts import noise_experiment as noise
from scripts import train_model as base
from scripts import generate_dataset as gen

LEVELS = (.15, .20)
SEEDS = (20261014, 20261015, 20261016)
ROOT = 20261020
BATCH = 128
OUTPUT = Path('runs/noise_extrapolation')
ARCHIVE = Path('results/noise_extrapolation')
TABLE = Path('paper/tables/noise_extrapolation.tex')


def rng(realization):
    return np.random.Generator(np.random.PCG64(np.random.SeedSequence(
        [ROOT, 2, realization])))


def array_hash(value):
    return hashlib.sha256(np.ascontiguousarray(value).tobytes()).hexdigest()


def condition_metrics(truth, prediction):
    if not np.isfinite(prediction).all():
        raise ValueError('Nonfinite prediction')
    errors = np.abs(prediction - truth) / truth
    result = {name: {stat: float(value) for stat, value in zip(
        ('median', 'mean', 'p95', 'max'),
        (np.median(errors[:, j]), errors[:, j].mean(),
         np.quantile(errors[:, j], .95), errors[:, j].max()))}
        for j, name in enumerate(gen.RANGES)}
    result['any_gt10'] = float(np.mean(np.any(errors > .10, axis=1)))
    result['any_gt50'] = float(np.mean(np.any(errors > .50, axis=1)))
    return result


def bank_predict(model, stats, x, rms, level, realization):
    stream = rng(realization)
    digests = {key: hashlib.sha256() for key in ('base_normals', 'perturbation', 'input')}
    predictions = []
    model.eval()
    with torch.no_grad():
        for start in range(0, len(x), BATCH):
            batch = x[start:start + BATCH]
            normals = stream.standard_normal(batch.shape, dtype=np.float32)
            perturbation = normals * np.float32(level) * rms[None, :, None]
            physical = batch + perturbation
            for key, value in zip(digests, (normals, perturbation, physical)):
                digests[key].update(value.tobytes())
            inputs = base.transform_inputs(physical, stats)
            predictions.append(base.decode(model(torch.from_numpy(inputs)).numpy(), stats))
    return np.concatenate(predictions), {k: v.hexdigest() for k, v in digests.items()}


def summarize(models):
    """Realization statistics -> seed averages -> mean and sample SD; fractions."""
    result = {}
    for level in LEVELS:
        result[str(level)] = {}
        for family in ('clean', 'augmented'):
            per_seed = {}
            for seed in SEEDS:
                rows = [c for c in models[f'{family}_{seed}']['conditions'] if c['level'] == level]
                if len(rows) != 3 or sorted(c['realization'] for c in rows) != [0, 1, 2]:
                    raise ValueError('Require exactly three distinct realizations')
                per_seed[str(seed)] = {
                    **{f'{p}_{stat}': float(np.mean([c['metrics'][p][stat] for c in rows]))
                       for p in gen.RANGES for stat in ('median', 'mean', 'p95', 'max')},
                    **{rate: float(np.mean([c['metrics'][rate] for c in rows]))
                       for rate in ('any_gt10', 'any_gt50')}}
            result[str(level)][family] = {
                key: {'mean': float(np.mean([s[key] for s in per_seed.values()])),
                      'sample_sd': float(np.std([s[key] for s in per_seed.values()], ddof=1)),
                      'per_seed': {seed: s[key] for seed, s in per_seed.items()}}
                for key in next(iter(per_seed.values()))}
    return result


def table_text(summary):
    lines = ['% Generated by scripts/noise_extrapolation.py; errors in percent.',
             r'\begin{tabular}{rlrrr}', r'\hline',
             r'Noise (\%) & Model & $R$ & $L$ & $C$ \\', r'\hline']
    for level in LEVELS:
        for family, label in (('clean', 'CMLP'), ('augmented', 'NMLP')):
            values = [summary[str(level)][family][f'{p}_median'] for p in gen.RANGES]
            cells = [f"${100*v['mean']:.3f} \\pm {100*v['sample_sd']:.3f}$" for v in values]
            lines.append(f'{level*100:.0f} & {label} & ' + ' & '.join(cells) + r' \\')
    return '\n'.join(lines + [r'\hline', r'\end{tabular}', ''])


def verify():
    archived_manifest = json.loads(Path('results/noise/manifest.json').read_text())
    archived_results = json.loads(Path('results/noise/results.json').read_text())
    hashes = {name: base.digest(Path('data') / name) for name in ('circuits.csv', 'waveforms.npz')}
    if hashes != archived_manifest['dataset_sha256']:
        raise ValueError('Dataset hashes differ from archive')
    original_path = Path('runs/mlp/model.pt')
    if base.digest(original_path) != archived_manifest['original_checkpoint_sha256']:
        raise ValueError('Original checkpoint hash differs')
    x, y, splits, _ = base.load_data(Path('data'))
    if x.shape != (10000, 2, 5001) or x.dtype != np.float32 or len(splits['test']) != 1500:
        raise ValueError('Unexpected original dataset shape/type/split')
    stats = base.fit_preprocessing(x, y, splits['train'])
    rms = noise.channel_rms(x, splits['train'])
    np.testing.assert_array_equal(rms, np.array(archived_manifest['channel_rms_physical'], dtype=np.float32))
    ids = np.array([r['sample_id'] for r in gen.read_metadata(Path('data/circuits.csv'))])
    checkpoints = {}
    for key in ('original',) + tuple(f'{f}_{s}' for s in SEEDS for f in ('clean', 'augmented')):
        path = original_path if key == 'original' else Path('runs/noise') / f'{key}.pt'
        record = archived_results[key]
        if base.digest(path) != record['checkpoint_sha256']:
            raise ValueError(f'Checkpoint SHA mismatch: {key}')
        ck = torch.load(path, map_location='cpu', weights_only=True)
        noise.verify_provenance(ck, hashes, gen.TIME)
        for name in stats:
            np.testing.assert_array_equal(ck['preprocessing'][name].numpy(), stats[name])
        prediction_path = Path('runs/noise') / f'{key}_predictions.npz'
        if base.digest(prediction_path) != record['predictions_sha256']:
            raise ValueError(f'Archived prediction SHA mismatch: {key}')
        with np.load(prediction_path, allow_pickle=False) as saved:
            for i, c in enumerate(record['test']):
                sl = slice(i * 1500, (i + 1) * 1500)
                np.testing.assert_array_equal(saved['sample_id'][sl], ids[splits['test']])
                np.testing.assert_array_equal(saved['truth'][sl], y[splits['test']])
                np.testing.assert_array_equal(saved['level'][sl], c['level'])
                np.testing.assert_array_equal(saved['realization'][sl], c['realization'])
                if saved['condition_noise_sha256'][i] != c['noise_sha256']:
                    raise ValueError('Archived noise hash mismatch')
        if key != 'original':
            family, seed = key.split('_')
            if (ck['seed'] != int(seed) or ck['noise']['augmented'] != (family == 'augmented') or
                    ck['noise']['levels'] != list(noise.LEVELS) or
                    ck['architecture'] != [10002, 128, 64, 3] or
                    ck['noise']['contract'] != archived_manifest['noise_contract'] or
                    ck['noise']['selection'] != 'equal mean standardized log-target MSE over fixed validation bank, one realization per level'):
                raise ValueError(f'Checkpoint identity/selection mismatch: {key}')
            np.testing.assert_array_equal(ck['noise']['channel_rms_physical'], rms.tolist())
            for name in ('best_epoch', 'best_validation_mse', 'clean_validation_mse', 'history'):
                if ck[name] != record['training'][name]:
                    raise ValueError(f'Archived selection mismatch: {key}/{name}')
            if (ck['best_validation_mse'] != min(r['validation_mse'] for r in ck['history']) or
                    ck['history'][ck['best_epoch'] - 1]['validation_mse'] != ck['best_validation_mse']):
                raise ValueError('Selected checkpoint epoch mismatch')
            checkpoints[key] = {'path': str(path), 'sha256': base.digest(path),
                                'best_epoch': ck['best_epoch'],
                                'best_validation_mse': ck['best_validation_mse']}
    return x[splits['test']], y[splits['test']], ids[splits['test']], rms, {
        'dataset_sha256': hashes, 'original_checkpoint_sha256': base.digest(original_path),
        'checkpoints': checkpoints, 'channel_rms_physical': rms.tolist(),
        'preprocessing': {k: v.tolist() for k, v in stats.items()},
        'splits': {s: {'count': len(index), 'ids_sha256': array_hash(ids[index]),
                       'labels_sha256': array_hash(y[index])} for s, index in splits.items()},
        'archived_records_sha256': {str(p): base.digest(p) for p in
            (Path('results/noise/manifest.json'), Path('results/noise/results.json'))}}


def report_text(results):
    lines = ['# Final unseen-amplitude Gaussian stress test', '',
             'Fullgrid5001, 50 ms, original 1,500 test circuits; six fixed checkpoints.',
             'All errors/rates below are percent: mean +/- sample SD over three seed',
             'averages, each averaging three realization statistics (not pooled errors).', '',
             '| Noise | Model | Statistic | R | L | C |', '|---|---|---|---|---|---|']
    for level in LEVELS:
        for family in ('clean', 'augmented'):
            summary = results['summary'][str(level)][family]
            for stat in ('median', 'mean', 'p95', 'max'):
                cells = [f"{100*summary[f'{p}_{stat}']['mean']:.3f} +/- {100*summary[f'{p}_{stat}']['sample_sd']:.3f}"
                         for p in gen.RANGES]
                lines.append(f'| {100*level:.0f}% | {family} | {stat} | ' + ' | '.join(cells) + ' |')
            for rate in ('any_gt10', 'any_gt50'):
                v = summary[rate]
                lines.append(f"| {100*level:.0f}% | {family} | {rate} | {100*v['mean']:.3f} +/- {100*v['sample_sd']:.3f} | — | — |")
    old = json.loads(Path('results/noise/results.json').read_text())
    lines += ['', '## Original 10% context (different streams, not same-realization paired)', '',
              'Historical MPS evaluation used root 20261018; new CPU evaluation uses root',
              '20261020. These are descriptive cross-amplitude comparisons, not paired',
              'realization differences. Original mean realization/seed medians R/L/C (%):']
    for family in ('clean', 'augmented'):
        values = [100 * np.mean([np.mean([c['regimes']['all']['relative_error'][p]['median']
                  for c in old[f'{family}_{seed}']['test'] if c['level'] == .1])
                  for seed in SEEDS]) for p in gen.RANGES]
        lines.append(f"- {family}: " + ' / '.join(f'{v:.3f}' for v in values))
    lines += ['', '## Interpretation and limits', '',
              'Augmentation reduces errors relative to matched clean controls at both new',
              'amplitudes, but errors increase beyond the original 10% context; this is not',
              'amplitude-invariant robustness. Individual condition metrics, including maxima',
              'and strict any-component >10%/>50% rates, are retained in results.json.',
              'The displayed max is an average of condition maxima, not a global maximum.',
              'The three realizations repeat the same 1,500 circuits, not 4,500 independent',
              'circuits. Three-seed SD is descriptive, not a confidence interval. No new',
              'parameter distribution, noise type, fitting, training, model selection or',
              'latency study was used. Two unseen Gaussian amplitudes do not establish',
              'unseen-type, hardware, model-mismatch or general OOD robustness.', '',
              'Prediction binaries are only in ignored runs/noise_extrapolation; their SHA256',
              'hashes are recorded in results.json. Provenance/stream hashes are in manifest.json.', '']
    return '\n'.join(lines)


def run():
    for path in (OUTPUT, ARCHIVE):
        if path.exists() and any(path.iterdir()):
            raise ValueError(f'Refusing to overwrite nonempty output: {path}')
    torch.set_num_threads(1)
    x, y, ids, rms, provenance = verify()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    ARCHIVE.mkdir(parents=True, exist_ok=True)
    manifest = {**provenance, 'versions': {'python': platform.python_version(),
                'numpy': np.__version__, 'torch': str(torch.__version__), 'platform': platform.platform()},
                'device': 'cpu', 'cpu_threads': torch.get_num_threads(), 'batch_size': BATCH,
                'levels': list(LEVELS), 'realizations': 3,
                'rng': 'PCG64(SeedSequence([20261020, 2, realization])); float32 C-order batches; reset per amplitude/model',
                'float32_order': 'normals * float32(level) * float32(original RMS); physical clean + perturbation; frozen transform/decode',
                'channel_order_units': ['current_a', 'capacitor_voltage_v'],
                'source_sha256': {p: base.digest(Path(p)) for p in
                    ('scripts/noise_extrapolation.py', 'docs/noise_extrapolation.md',
                     'scripts/noise_experiment.py', 'scripts/train_model.py')},
                'condition_hashes': {}}
    results = {'models': {}}
    reference = None
    for key, ck in provenance['checkpoints'].items():
        print(f'Evaluating {key}', flush=True)
        model, stats = base.load_checkpoint(Path(ck['path']), 'cpu')
        rows, predictions, hashes = [], [], {}
        for level in LEVELS:
            for r in range(3):
                predicted, digest = bank_predict(model, stats, x, rms, level, r)
                rows.append({'level': level, 'realization': r,
                             'metrics': condition_metrics(y, predicted), 'hashes': digest})
                predictions.append(predicted)
                hashes[f'{level}/{r}'] = digest
        if reference is not None and hashes != reference:
            raise ValueError('Cross-model pairing failed')
        reference = hashes
        for r in range(3):
            if hashes[f'0.15/{r}']['base_normals'] != hashes[f'0.2/{r}']['base_normals']:
                raise ValueError('Cross-amplitude base pairing failed')
        path = OUTPUT / f'{key}_predictions.npz'
        np.savez_compressed(path, prediction=np.stack(predictions), truth=y, sample_id=ids,
                            level=np.repeat(LEVELS, 3), realization=np.tile(np.arange(3), 2),
                            target_names=np.array(list(gen.RANGES)), model_key=np.array(key))
        results['models'][key] = {'checkpoint_sha256': ck['sha256'], 'conditions': rows,
                                  'predictions_path': str(path), 'predictions_sha256': base.digest(path)}
    manifest['condition_hashes'] = reference
    results['summary'] = summarize(results['models'])
    gen.write_json(ARCHIVE / 'manifest.json', manifest)
    gen.write_json(ARCHIVE / 'results.json', results)
    (ARCHIVE / 'report.md').write_text(report_text(results))
    TABLE.write_text(table_text(results['summary']))
    print(f'Saved {ARCHIVE} and {TABLE}', flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check-table', action='store_true', help='Read-only generation check; no evaluation')
    args = parser.parse_args()
    if args.check_table:
        results = json.loads((ARCHIVE / 'results.json').read_text())
        if TABLE.read_text() != table_text(summarize(results['models'])):
            raise SystemExit('Generated noise-extrapolation table is stale')
        print('Noise-extrapolation table is current')
    else:
        run()


if __name__ == '__main__':
    main()
